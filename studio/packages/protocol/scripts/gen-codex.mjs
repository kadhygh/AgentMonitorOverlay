// Regenerates packages/protocol/src/codex from the installed Codex CLI (`codex app-server generate-ts`).
// Run with `npm run gen:codex -w @amo-studio/protocol` after a Codex upgrade.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const outDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "codex");
// codex is a .cmd shim on Windows; the arguments here are fixed, so running through the shell is safe.
const version = execFileSync("codex --version", { encoding: "utf8", shell: true }).trim();
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
execFileSync(`codex app-server generate-ts --out "${outDir}"`, { stdio: "inherit", shell: true });

// The generator emits extensionless relative specifiers; NodeNext resolution needs explicit .js ones.
function addExtensions(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) { addExtensions(file); continue; }
    if (!entry.name.endsWith(".ts")) continue;
    const src = fs.readFileSync(file, "utf8");
    const out = src.replace(/from "(\.{1,2}\/[^"]+)"/g, (_, spec) => {
      const target = path.resolve(dir, spec);
      const isDir = fs.existsSync(target) && fs.statSync(target).isDirectory();
      return `from "${spec}${isDir ? "/index.js" : ".js"}"`;
    });
    if (out !== src) fs.writeFileSync(file, out);
  }
}
addExtensions(outDir);
fs.writeFileSync(path.join(outDir, "VERSION.ts"), `// Generated by scripts/gen-codex.mjs. Do not edit.\nexport const CODEX_PROTOCOL_SOURCE = ${JSON.stringify(version)};\n`);
console.log(`generated Codex bindings from ${version} into ${outDir}`);
